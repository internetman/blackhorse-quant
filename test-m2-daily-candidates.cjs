const assert = require('node:assert/strict');
const {model} = require('./m2-daily-candidates.js');
const fixture = () => ({schemaVersion:1,asOfDate:'2026-11-11',mode:'replay',candidates:Array.from({length:8},(_,i)=>({code:String(600000+i),asOfDate:'2026-11-11',confirmedSignal:true}))});
assert.match(model(fixture(),'2026-11-12').label,/历史试跑/);
assert.equal(model(fixture(),'2026-11-12').candidates.length,8);
const d=fixture(); d.mode='close';
assert.match(model(d,'2026-11-12').label,/滞后/);
assert.match(model(d,null).label,/待核/);
assert.match(model(d,'2026-11-10').label,/日期待核/);
assert.match(model(d,'2026-11-11').label,/待人工/);
d.candidates.push({...d.candidates[0]},{code:'600099',asOfDate:'2026-11-10'});
assert.equal(model(d,'2026-11-12').candidates.length,8);
assert.throws(()=>model({schemaVersion:1,asOfDate:'bad',candidates:[]}));
d.candidates=[]; assert.equal(model(d,'2026-11-12').candidates.length,0);
console.log('Candidate date states, no hard cap, dedupe, empty and mismatched date tests passed.');
const a=fixture();
assert.equal(model(a,'2026-11-12',code=>code==='600000').candidates.length,7);
a.asOfDate='2026-11-12';a.candidates.forEach(c=>c.asOfDate=a.asOfDate);
assert.equal(model(a,'2026-11-12',code=>code==='600000').candidates.some(c=>c.code==='600000'),false);
assert.equal(model(a,'2026-11-12',()=>false).candidates.length,8);
console.log('Archive exclusion survives date change; explicit restore permits resurfacing.');
